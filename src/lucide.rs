/// Maps legacy emoji page icons to Lucide glyphs (unknown strings are returned unchanged).
pub fn migrate(icon: &str) -> String {
    let t = icon.trim().trim_end_matches('\u{fe0f}');
    match t {
        "📄" => FILE_TEXT.to_owned(),
        "📝" => NOTEBOOK.to_owned(),
        "✅" => SQUARE_CHECK.to_owned(),
        "📚" => BOOK_OPEN.to_owned(),
        "💡" => LIGHTBULB.to_owned(),
        "🎯" => TARGET.to_owned(),
        "🚀" => ROCKET.to_owned(),
        "⭐" => STAR.to_owned(),
        "🔥" => FLAME.to_owned(),
        "🌱" => SPROUT.to_owned(),
        "🎨" => PALETTE.to_owned(),
        "📅" => CALENDAR_DAYS.to_owned(),
        "🏠" => HOUSE.to_owned(),
        "💼" => BRIEFCASE.to_owned(),
        "📎" => PIN.to_owned(),
        "❤" => HEART.to_owned(),
        "☀" => SUN.to_owned(),
        "☕" => COFFEE.to_owned(),
        "⚡" => ZAP.to_owned(),
        "✈" => PLANE.to_owned(),
        "🔒" => LOCK.to_owned(),
        "🔔" => BELL.to_owned(),
        "🎵" => MUSIC.to_owned(),
        "🌍" => GLOBE.to_owned(),
        "📊" => CHART_COLUMN.to_owned(),
        "📁" => FOLDER.to_owned(),
        "🎬" => VIDEO.to_owned(),
        "🛠" => WRENCH.to_owned(),
        "📌" => PIN.to_owned(),
        "💬" => MESSAGE_SQUARE.to_owned(),
        "🏆" => TROPHY.to_owned(),
        "🎓" => GRADUATION_CAP.to_owned(),
        "💰" => WALLET.to_owned(),
        "🔍" => SEARCH.to_owned(),
        "📖" => BOOK_OPEN.to_owned(),
        "📷" => CAMERA.to_owned(),
        "📋" => CLIPBOARD.to_owned(),
        "📦" => PACKAGE.to_owned(),
        "🗑" => TRASH_2.to_owned(),
        _ => icon.to_owned(),
    }
}

